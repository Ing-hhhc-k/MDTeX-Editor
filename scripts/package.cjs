const fs = require('node:fs/promises')
const path = require('node:path')
const {execFileSync}=require('node:child_process')
const {zipSync}=require('fflate')
;(async () => {
  const root = path.resolve(__dirname, '..')
  const distribution = path.join(root, 'release', 'MDTeX')
  const target = path.join(distribution, '_internal')
  const runtime = path.dirname(require('electron'))
  await fs.mkdir(target, {recursive:true})
  await fs.cp(runtime, target, {recursive:true})
  const appDir = path.join(target, 'resources', 'app')
  await fs.mkdir(appDir, {recursive:true})
  await fs.cp(path.join(root,'dist'),path.join(appDir,'dist'),{recursive:true})
  await fs.cp(path.join(root,'dist-electron'),path.join(appDir,'electron'),{recursive:true})
  const pkg = require('../package.json')
  await fs.writeFile(path.join(appDir,'package.json'),JSON.stringify({name:pkg.name,version:pkg.version,main:pkg.main,productName:'MDTeX'}))
  await fs.rename(path.join(target,'electron.exe'),path.join(target,'MDTeX.exe'))
  await fs.copyFile(path.join(root,'README.md'),path.join(distribution,'使用说明.md'))
  await fs.copyFile(path.join(root,'CHANGELOG.md'),path.join(distribution,'CHANGELOG.md'))
  await fs.copyFile(path.join(root,'ROADMAP.md'),path.join(distribution,'ROADMAP.md'))
  const compiler=path.join(process.env.WINDIR||'C:/Windows','Microsoft.NET/Framework64/v4.0.30319/csc.exe')
  const launcher=path.join(root,'MDTeX.exe')
  execFileSync(compiler,['/nologo','/target:winexe','/reference:System.Windows.Forms.dll','/out:'+launcher,path.join(root,'scripts/Launcher.cs')],{stdio:'pipe',windowsHide:true})
  await fs.copyFile(launcher,path.join(distribution,'MDTeX.exe'))
  const entries=Object.create(null)
  async function add(dir,prefix=''){for(const file of await fs.readdir(dir,{withFileTypes:true})){const key=prefix+file.name,p=path.join(dir,file.name);if(file.isDirectory())await add(p,key+'/');else entries[key]=await fs.readFile(p)}}
  await add(path.join(distribution,'_internal'),'_internal/')
  for(const name of ['MDTeX.exe','使用说明.md','CHANGELOG.md','ROADMAP.md'])entries[name]=await fs.readFile(path.join(distribution,name))
  const archive=path.join(root,'MDTeX-Editor-'+pkg.version+'-win-x64.zip')
  await fs.writeFile(archive,zipSync(entries,{level:6}))
  console.log('根目录启动程序：'+launcher)
  console.log('Windows 免安装包：'+archive)
})().catch(error=>{console.error(error);process.exitCode=1})
