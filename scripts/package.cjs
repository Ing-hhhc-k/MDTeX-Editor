const fs = require('node:fs/promises')
const path = require('node:path')
;(async () => {
  const root = path.resolve(__dirname, '..')
  const target = path.join(root, 'release', 'MDTeX')
  const runtime = path.dirname(require('electron'))
  await fs.mkdir(target, {recursive:true})
  await fs.cp(runtime, target, {recursive:true})
  const appDir = path.join(target, 'resources', 'app')
  await fs.mkdir(appDir, {recursive:true})
  await fs.cp(path.join(root,'dist'),path.join(appDir,'dist'),{recursive:true})
  await fs.cp(path.join(root,'electron'),path.join(appDir,'electron'),{recursive:true})
  const pkg = require('../package.json')
  await fs.writeFile(path.join(appDir,'package.json'),JSON.stringify({name:pkg.name,version:pkg.version,main:pkg.main,productName:'MDTeX'}))
  await fs.rename(path.join(target,'electron.exe'),path.join(target,'MDTeX.exe'))
  await fs.copyFile(path.join(root,'README.md'),path.join(target,'使用说明.md'))
  await fs.copyFile(path.join(root,'CHANGELOG.md'),path.join(target,'CHANGELOG.md'))
  await fs.copyFile(path.join(root,'ROADMAP.md'),path.join(target,'ROADMAP.md'))
  console.log('Windows 免安装版已生成：' + path.join(target,'MDTeX.exe'))
})().catch(error=>{console.error(error);process.exitCode=1})
