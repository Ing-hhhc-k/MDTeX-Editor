const { contextBridge, ipcRenderer } = require('electron')
contextBridge.exposeInMainWorld('desktop', {
  initialState: ipcRenderer.sendSync('storage:bootstrap'),
  ready: () => ipcRenderer.invoke('app:ready'),
  copyText: text => ipcRenderer.invoke('clipboard:write-text', text),
  saveSession: data => {const result=ipcRenderer.sendSync('storage:session',data);if(result.error)throw new Error(result.error);return result},
  setPreference: (key,value) => ipcRenderer.invoke('storage:preference',{key,value}),
  openDataFolder: () => ipcRenderer.invoke('storage:open'),
  installUpdate: () => ipcRenderer.invoke('app:install-update'),
  onUpdateProgress: fn => {const listener=(_,value)=>fn(value);ipcRenderer.on('app:update-progress',listener);return ()=>ipcRenderer.removeListener('app:update-progress',listener)},
  open: () => ipcRenderer.invoke('file:open'),
  readFile: data=>ipcRenderer.invoke('file:read',data),
  listDefaultDocuments: ()=>ipcRenderer.invoke('file:list-defaults'),
  deleteDefaultDocument: data=>ipcRenderer.invoke('file:delete-default',data),
  confirmClose: data=>ipcRenderer.invoke('file:confirm-close',data),
  confirmReload: data=>ipcRenderer.invoke('file:confirm-reload',data),
  confirmUpdate: data=>ipcRenderer.invoke('file:confirm-update',data),
  onSaveBeforeClose: fn=>{const listener=()=>fn();ipcRenderer.on('app:save-before-close',listener);return ()=>ipcRenderer.removeListener('app:save-before-close',listener)},
  finishClose: ()=>ipcRenderer.invoke('app:finish-close'),
  setTheme: theme => ipcRenderer.invoke('app:theme',theme),
  checkUpdate: options => ipcRenderer.invoke('app:check-update',options),
  downloadUpdate: () => ipcRenderer.invoke('app:download-update'),
  save: data => ipcRenderer.invoke('file:save', data),
  draftSync: data => ipcRenderer.invoke('draft:sync', data),
  deleteDraft: data => ipcRenderer.invoke('draft:delete', data),
  detachDraft: data => ipcRenderer.invoke('draft:detach', data),
  importImage: data => ipcRenderer.invoke('image:import', data),
  previewImage: data => ipcRenderer.invoke('image:preview', data),
  exportZip: data => ipcRenderer.invoke('file:export', data),
  workspace: Object.fromEntries(['open','list','read','create','rename','delete'].map(name=>[name,(...args)=>ipcRenderer.invoke('workspace:'+name,...args)])),
})
