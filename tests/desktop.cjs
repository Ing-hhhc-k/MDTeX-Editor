const { _electron: electron } = require('@playwright/test')
const assert = require('node:assert/strict')
const fs = require('node:fs/promises')
;(async () => {
  const env = { ...process.env, MDTEX_TEST:'1' }; delete env.ELECTRON_RUN_AS_NODE
  const app = await electron.launch({ args:['.'], env, timeout:60000 })
  try {
    const page = await app.firstWindow()
    const errors=[]
    page.on('pageerror', error=>{ errors.push(error.message); console.error('Renderer:',error.message) })
    page.on('console', message=>{if(message.type()==='error')console.error('Console:',message.text())})
    await page.reload()
    await page.waitForTimeout(1000)
    await page.waitForSelector('.prose h1')
    assert.match(await page.locator('.prose h1').innerText(), /让思考/)
    assert.equal(await page.locator('.blockMath').count(),2)
    await app.evaluate(({BrowserWindow})=>BrowserWindow.getAllWindows()[0].showInactive())
    await page.screenshot({path:'test-results/editor.png',fullPage:true,timeout:10000})
    await page.getByRole('button',{name:'阅读',exact:true}).click()
    assert.equal(await page.locator('.prose').getAttribute('contenteditable'),'false')
    await page.keyboard.press('Control+Alt+n')
    assert.doesNotMatch(await page.locator('.prose h1').innerText(),/^1 /)
    await page.keyboard.press('Control+Shift+m')
    assert.equal(await page.getByRole('dialog').count(),0)
    await page.getByRole('button',{name:'源码',exact:true}).click()
    const source=page.getByRole('textbox',{name:'Markdown 源码'})
    const fixture='# 测试文档\n\n## 第一节\n\n正文 **加粗**，行内 $x^2$。\n\n$$\n\\frac{a}{b}\n$$\n\n| 列一 | 列二 |\n| --- | --- |\n| A | B |\n\n```js\nconst x = 1\n```\n\n## 第二节\n'
    await source.fill(fixture)
    await page.getByRole('button',{name:'编辑',exact:true}).click()
    assert.equal(await page.locator('.prose table tr').count(),2)
    assert.equal(await page.locator('.blockMath').count(),1)
    await page.keyboard.press('Control+Alt+n')
    assert.equal(await page.locator('.prose h2').first().innerText(),'1.1 第一节')
    assert.equal(await page.locator('.prose h2').last().innerText(),'1.2 第二节')
    await page.keyboard.press('Control+Alt+Shift+n')
    assert.equal(await page.locator('.prose h2').first().innerText(),'第一节')
    await page.getByRole('button',{name:'折叠代码',exact:true}).click()
    assert.equal(await page.locator('.code-wrapper.is-collapsed').count(),1)
    await page.getByRole('button',{name:'展开代码',exact:true}).click()
    await page.locator('.prose table td').first().click({button:'right'})
    await page.getByRole('button',{name:'在下方插入行',exact:true}).click()
    assert.equal(await page.locator('.prose table tr').count(),3)
    await page.locator('.prose table td').first().hover()
    await page.getByRole('button',{name:'在表格右侧添加列'}).click()
    assert.equal(await page.locator('.prose table tr').first().locator('th,td').count(),3)
    await page.locator('.blockMath').dblclick()
    await page.getByRole('textbox',{name:'LaTeX 源码'}).fill('x = y + z')
    await page.getByRole('button',{name:'更新公式',exact:true}).click()
    await page.getByRole('button',{name:'源码',exact:true}).click()
    assert.match(await source.inputValue(),/x = y \+ z/)
    assert.match(await source.inputValue(),/```js/)
    await page.getByRole('button',{name:'分屏',exact:true}).click()
    await source.fill('# 双向编辑\n\n这是一段正文。\n')
    await page.waitForTimeout(450)
    await page.locator('.prose p').first().click()
    await page.keyboard.press('End')
    await page.keyboard.type('Added')
    await page.waitForTimeout(350)
    await page.keyboard.type('Again')
    assert.match(await source.inputValue(),/AddedAgain/)
    // Read-only state must never mutate content when clicking preview.
    await page.getByRole('button',{name:'阅读',exact:true}).click()
    await page.locator('.prose p').first().click()
    await page.keyboard.type('SHOULD_NOT_APPEAR')
    assert.doesNotMatch(await page.locator('.prose').innerText(),/SHOULD_NOT_APPEAR/)
    await page.getByRole('button',{name:'源码',exact:true}).click()
    await source.fill('# 文件保存测试\n\n需要持久化的正文。\n')
    const path=require('node:path')
    const target=path.resolve('test-results/saved.md')
    const targetAs=path.resolve('test-results/saved-as.md')
    await app.evaluate(({dialog},dest)=>{dialog.showSaveDialog=async()=>({canceled:false,filePath:dest})},target)
    await page.keyboard.press('Control+s')
    await page.waitForTimeout(700)
    assert.match(await fs.readFile(target,'utf8'),/需要持久化的正文/)
    await source.fill('# 文件保存测试\n\n已修改，覆盖原文件。\n')
    await page.keyboard.press('Control+s')
    await page.waitForTimeout(700)
    assert.match(await fs.readFile(target,'utf8'),/已修改，覆盖原文件/)
    await app.evaluate(({dialog},dest)=>{dialog.showSaveDialog=async()=>({canceled:false,filePath:dest})},targetAs)
    await page.keyboard.press('Control+Shift+s')
    await page.waitForTimeout(700)
    assert.equal(await fs.readFile(targetAs,'utf8'),await fs.readFile(target,'utf8'))
    const openTarget=path.resolve('test-results/open.md')
    await fs.writeFile(openTarget,'# 打开测试\n\n打开文件后的内容。\n')
    await app.evaluate(({dialog},dest)=>{dialog.showOpenDialog=async()=>({canceled:false,filePaths:[dest]})},openTarget)
    await page.keyboard.press('Control+o')
    await page.waitForTimeout(500)
    assert.match(await source.inputValue(),/打开文件后的内容/)
    await source.fill('# 草稿恢复测试\n\n草稿重新加载后仍存在。\n')
    await page.keyboard.press('Control+s')
    await page.waitForTimeout(800)
    await page.reload()
    await page.waitForSelector('.prose h1')
    assert.equal(await page.locator('.prose h1').innerText(),'草稿恢复测试')
    await page.getByRole('button',{name:'源码',exact:true}).click()
    await source.click()
    await page.keyboard.press('Control+End')
    await page.keyboard.press('Control+Shift+m')
    await page.getByRole('button',{name:'分式',exact:true}).click()
    await page.getByRole('button',{name:'插入公式',exact:true}).click()
    assert.match(await source.inputValue(),/\$\$\n\\frac\{a\}\{b\}\n\$\$/)
    assert.deepEqual(errors,[])
    console.log('PASS: desktop rendering, formula insertion/round-trip/edit, read-only, numbering shortcuts, table row/column, folding, split editing, open/save/overwrite/save-as, draft restoration')
  } finally {
    await app.evaluate(({ BrowserWindow,app })=> { for(const win of BrowserWindow.getAllWindows())win.destroy(); app.quit() }).catch(()=>{})
    await app.close().catch(()=>{})
  }
})().catch(error=>{console.error(error);process.exitCode=1})
