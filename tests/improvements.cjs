const { _electron } = require('@playwright/test')
const assert = require('node:assert/strict')
const path = require('node:path')
;(async () => {
  const env = { ...process.env, MDTEX_TEST: '1' }; delete env.ELECTRON_RUN_AS_NODE
  const app = await _electron.launch({args:['.'],env,timeout:60000})
  try {
    const page = await app.firstWindow()
    const errors=[]; await app.evaluate(({dialog})=>{dialog.showMessageBox=async()=>({response:1});dialog.showMessageBoxSync=()=>1}); page.on('pageerror',e=>errors.push(e.message))
    await page.waitForSelector('.prose h1')
    await app.evaluate(({BrowserWindow})=>BrowserWindow.getAllWindows()[0].showInactive())
    const source=page.getByRole('textbox',{name:'Markdown 源码'})
    const mode=name=>page.getByRole('button',{name,exact:true}).click()
    const fixture='# 章一\n\n## 节一\n\n正文不变。\n\n## 节二 **粗体**\n\n### 子节\n\n```python\nconst answer = 42; // example\n```\n\n# 章二\n'
    await mode('源码'); await source.fill(fixture); await mode('编辑')
    await page.locator('.prose h2').last().click()
    await page.getByRole('button',{name:'标题编号选项',exact:true}).click()
    await page.getByRole('menuitem',{name:/仅编号当前标题/}).click()
    assert.equal(await page.locator('.prose h2').last().innerText(),'1.2 节二 粗体')
    assert.equal(await page.locator('.prose h2').first().innerText(),'节一')
    assert.equal(await page.locator('.prose h1').first().innerText(),'章一')
    assert.equal(await page.locator('.prose h3').innerText(),'子节')
    assert.equal(await page.locator('.prose h2 strong').innerText(),'粗体')
    await page.locator('.prose h2').last().click()
    await page.keyboard.press('Control+Alt+Shift+h')
    assert.equal(await page.locator('.prose h2').last().innerText(),'节二 粗体')
    await page.keyboard.press('Control+Alt+h')
    assert.equal(await page.locator('.prose h2').last().innerText(),'1.2 节二 粗体')
    await page.keyboard.press('Control+Alt+n')
    assert.equal(await page.locator('.prose h1').last().innerText(),'2 章二')
    await page.locator('.prose h2').first().click()
    await page.getByRole('button',{name:'标题编号选项',exact:true}).click()
    await page.getByRole('menuitem',{name:/移除当前标题编号/}).click()
    assert.equal(await page.locator('.prose h2').first().innerText(),'节一')
    assert.equal(await page.locator('.prose h2').last().innerText(),'1.2 节二 粗体')
    await page.locator('.prose p').filter({hasText:'正文不变'}).click()
    await page.keyboard.press('End'); await page.keyboard.type(' more')
    assert.equal(await page.locator('.prose h2').first().innerText(),'节一')
    // Invalid scope leaves all heading text unchanged.
    const before=await page.locator('.prose h1,.prose h2,.prose h3').allTextContents()
    await page.keyboard.press('Control+Alt+h')
    assert.deepEqual(await page.locator('.prose h1,.prose h2,.prose h3').allTextContents(),before)
    const language=page.getByRole('combobox',{name:'代码语言'})
    await language.selectOption('javascript')
    assert.equal(await page.locator('.code-wrapper .hljs-keyword').first().innerText(),'const')
    const codeText=await page.locator('.code-wrapper pre').innerText()
    await language.selectOption('sql')
    assert.equal(await page.locator('.code-wrapper pre').innerText(),codeText)
    await page.getByRole('button',{name:'折叠代码',exact:true}).click()
    await language.selectOption('cpp')
    assert.equal(await page.locator('.code-wrapper.is-collapsed').count(),1)
    await page.getByRole('button',{name:'展开代码',exact:true}).click()
    await mode('源码'); assert.match(await source.inputValue(),/```cpp/)
    await source.fill('# 多语言\n\n```matlab\nx = zeros(3);\n```\n\n```powershell\nGet-ChildItem -Path .\n```\n\n```latex\n\\frac{a}{b}\n```\n\n```custom-lang\nkeep this text\n```\n')
    await mode('编辑')
    assert.equal(await page.locator('.code-wrapper').count(),4)
    assert.equal(await page.locator('.code-wrapper .hljs-built_in,.code-wrapper .hljs-keyword').count()>0,true)
    await mode('源码'); assert.match(await source.inputValue(),/```custom-lang/)
    await mode('阅读')
    for(const select of await page.getByRole('combobox',{name:'代码语言'}).all()) assert.equal(await select.isDisabled(),true)
    const markdownBeforeZoom=await page.locator('.prose').innerText()
    await page.getByRole('button',{name:'放大页面',exact:true}).click()
    assert.equal(await page.getByRole('button',{name:'重置缩放'}).innerText(),'120%')
    await page.keyboard.press('Control+Equal')
    assert.equal(await page.getByRole('button',{name:'重置缩放'}).innerText(),'130%')
    await page.keyboard.press('Control+Minus')
    assert.equal(await page.getByRole('button',{name:'重置缩放'}).innerText(),'120%')
    await page.keyboard.press('Control+0')
    assert.equal(await page.getByRole('button',{name:'重置缩放'}).innerText(),'100%')
    await page.getByRole('combobox',{name:'页面宽度'}).selectOption('wide')
    assert.equal(await page.locator('.paper').evaluate(el=>el.style.maxWidth),'none')
    await page.getByRole('combobox',{name:'页面宽度'}).selectOption('compact')
    assert.equal(await page.locator('.paper').evaluate(el=>el.style.maxWidth),'850px')
    await page.getByRole('combobox',{name:'页面宽度'}).selectOption('standard')
    await page.getByRole('button',{name:'放大页面',exact:true}).click()
    assert.equal(await page.locator('.prose').innerText(),markdownBeforeZoom)
    await app.evaluate(({dialog},dest)=>{dialog.showSaveDialog=async()=>({canceled:false,filePath:dest})},path.resolve('test-results/improvements.md'))
    await page.keyboard.press('Control+s'); await page.waitForTimeout(800)
    await page.reload(); await page.waitForSelector('.prose h1')
    assert.equal(await page.getByRole('button',{name:'重置缩放'}).innerText(),'110%')
    assert.equal(await page.getByRole('combobox',{name:'页面宽度'}).inputValue(),'standard')
    await page.getByRole('button',{name:'放大页面',exact:true}).click()
    await page.getByRole('combobox',{name:'页面宽度'}).selectOption('wide')
    await page.screenshot({path:'test-results/improvements.png',timeout:10000})
    assert.deepEqual(errors,[])
    console.log('PASS: scoped numbering, formatting preservation, global/single interaction, language selection/highlighting/round-trip, folding, read-only, zoom shortcuts/width/persistence')
  } finally {
    await app.evaluate(({BrowserWindow,app})=>{for(const win of BrowserWindow.getAllWindows())win.destroy();app.quit()}).catch(()=>{})
    await app.close().catch(()=>{})
  }
})().catch(e=>{console.error(e);process.exitCode=1})
